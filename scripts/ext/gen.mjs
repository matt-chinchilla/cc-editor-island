// The files the wave units never edit, generated from the built ins and every
// unit's file (bridge/ext/README.md). Run at the join, once every unit landed:
//   node scripts/ext/gen.mjs            write bridge/ops.json, bridge/exports.json and PROTOCOL.md's unit parts
//   node scripts/ext/gen.mjs --check    write nothing; exit 1 when any of them would change
// bridge/ops.json is the built ins (bridge/ops.builtin.json) then every unit's
// ops sorted; bridge/exports.json the built in jobs (bridge/exports.builtin.json)
// then every unit's sorted. PROTOCOL.md takes each unit's bridge/ext/<unit>.md:
// its `requests`, `codes` and `events` lines go at the end of the request table,
// the error codes table and the events list, each tagged with the unit
// (`<!-- ext:<unit> -->`), and its `section` between the two section markers,
// in unit id order. A `codes` row whose code the table has already (a built
// in code, or an earlier unit's) is not added again: the first row stands.
// A `notes <op>` part's list items go at the end of the section of an op
// that ships (the `### ` heading naming it), each tagged with the unit. scripts/build.mjs reads the ops and the jobs through
// collect() as well, so island.json lists every landed unit's ops even before
// the files here are regenerated.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
export const OPS_PATH = 'bridge/ops.json';
export const EXPORTS_PATH = 'bridge/exports.json';
export const PROTOCOL_PATH = 'PROTOCOL.md';
const EXT_DIR = 'bridge/ext';
/** PROTOCOL.md as it stands in this checkout. */
export const readProtocol = () => readFileSync(join(ROOT, PROTOCOL_PATH), 'utf8');
export const SECTIONS_BEGIN = '<!-- ext sections: generated by scripts/ext/gen.mjs from bridge/ext/<unit>.md; never edit between these lines -->';
export const SECTIONS_END = '<!-- ext sections end -->';
/** The marker after each table or list the units add lines to. */
export const ROWS_MARK = (part) => `<!-- ext ${part}: the lines above tagged ext:<unit> are generated by scripts/ext/gen.mjs from bridge/ext/<unit>.md -->`;
export const PARTS = ['requests', 'codes', 'events'];
const TAG_RE = /<!-- ext:[a-z0-9-]+ -->/;
/** The notice lines a fragment starts with (scripts/notices.mjs checks them); never copied into PROTOCOL.md. */
const NOTICE_RE = /^<!--\s*(Copyright \(C\) 2026 Circuit Center Inc|SPDX-License-Identifier: [A-Za-z0-9.+-]+)\s*-->$/;

/** The registry through Vite (its glob), as the island's bundle sees it. */
export async function collect() {
  const { createServer } = await import('vite');
  const server = await createServer({ root: ROOT, configFile: join(ROOT, 'vite.config.ts'), logLevel: 'error', appType: 'custom', server: { middlewareMode: true, hmr: false, ws: false, watch: null }, optimizeDeps: { noDiscovery: true, include: [] } });
  try {
    const m = await server.ssrLoadModule('/bridge/ext/registry.ts');
    const reg = m.REGISTRY;
    return {
      problems: [...reg.problems],
      units: reg.units.map((u) => u.unit),
      ops: m.requestOps(reg),
      exportJobs: m.exportJobs(reg),
      capNames: Object.fromEntries(reg.capNames),
      events: Object.fromEntries([...reg.events].map(([t, e]) => [t, e.keys])),
      heldRows: m.heldActions(reg).map((h) => ({ action: h.action, frames: [...h.frames], cap: h.cap })),
      frames: [...reg.frames.keys()],
      asks: Object.fromEntries(reg.asks),
      pending: Object.fromEntries(reg.pending),
    };
  } finally {
    await server.close();
  }
}

/** One fragment read into its parts: { requests, codes, events: string[], section: string, notes: { [op]: string[] } }. */
export function readFragment(unit, text) {
  const parts = { requests: [], codes: [], events: [], section: [] };
  const notes = {};
  let at = null;
  for (const line of text.split('\n')) {
    const m = /^<!--\s*part:\s*([a-z]+)(?:\s+([a-z][A-Za-z0-9.]*))?\s*-->$/.exec(line.trim());
    if (m != null) {
      if (m[1] === 'notes' && m[2] != null) { at = `notes ${m[2]}`; notes[m[2]] ??= []; continue; }
      if (!(m[1] in parts) || m[2] != null) throw new Error(`bridge/ext/${unit}.md: no part '${m[1]}${m[2] != null ? ` ${m[2]}` : ''}' (requests, codes, events, section, notes <op>)`);
      at = m[1];
      continue;
    }
    if (NOTICE_RE.test(line.trim())) continue;
    if (at == null) { if (line.trim() !== '') throw new Error(`bridge/ext/${unit}.md: text before the first part marker`); continue; }
    if (at.startsWith('notes ')) { if (line.trim() !== '') notes[at.slice('notes '.length)].push(line); continue; }
    parts[at].push(line);
  }
  for (const [op, list] of Object.entries(notes)) for (const l of list) if (!l.startsWith('- ')) throw new Error(`bridge/ext/${unit}.md: notes ${op} lines are list items`);
  const lines = (p) => parts[p].filter((l) => l.trim() !== '');
  for (const p of ['requests', 'codes']) for (const l of lines(p)) if (!l.startsWith('|') || !l.endsWith('|')) throw new Error(`bridge/ext/${unit}.md: ${p} lines are table rows`);
  for (const l of lines('events')) if (!l.startsWith('- ')) throw new Error(`bridge/ext/${unit}.md: events lines are list items`);
  const section = parts.section.join('\n').trim();
  return { requests: lines('requests'), codes: lines('codes'), events: lines('events'), section, notes };
}

/** A table row's first cell (`| \`busy\` | ... |` is `busy`). */
const firstCell = (row) => row.split('|')[1]?.trim().replace(/^`|`$/g, '') ?? '';

/** Every fragment of the checkout, by unit id. */
export function readFragments(root = ROOT) {
  const dir = join(root, EXT_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md').sort()
    .map((f) => ({ unit: f.slice(0, -3), ...readFragment(f.slice(0, -3), readFileSync(join(dir, f), 'utf8')) }));
}

/** PROTOCOL.md with the units' parts put in (every earlier tagged line and section taken out first). */
export function assembleProtocol(text, fragments) {
  let lines = text.split('\n').filter((l) => !TAG_RE.test(l));
  for (const part of PARTS) {
    const mark = lines.indexOf(ROWS_MARK(part));
    if (mark < 0) throw new Error(`PROTOCOL.md has no marker for ${part}`);
    let last = mark - 1;
    while (last >= 0 && lines[last].trim() === '') last--;
    // The codes the table holds already: a unit's row for one of them is not added again.
    const seen = new Set();
    if (part === 'codes') for (let i = last; i >= 0 && lines[i].startsWith('|'); i--) seen.add(firstCell(lines[i]));
    const add = fragments.flatMap((f) => f[part].filter((l) => {
      if (part !== 'codes') return true;
      const code = firstCell(l);
      if (seen.has(code)) return false;
      seen.add(code);
      return true;
    }).map((l) => (part === 'events' ? `${l} <!-- ext:${f.unit} -->` : `${l.slice(0, -1).trimEnd()} <!-- ext:${f.unit} --> |`)));
    lines = [...lines.slice(0, last + 1), ...add, ...lines.slice(last + 1)];
  }
  // A unit's notes at the end of the section of an op that ships.
  for (const f of fragments) {
    for (const [op, list] of Object.entries(f.notes ?? {})) {
      if (list.length === 0) continue;
      // The op's own heading, else its family's (`sim.run` is under "The simulator: sim.*").
      const named = (name) => new RegExp(`(^|[\\s\`(])${name.replace(/[.*]/g, (c) => `\\${c}`)}($|[\\s\`),:])`);
      const find = (re) => lines.findIndex((l) => l.startsWith('### ') && re.test(l.slice(4)));
      let head = find(named(op));
      if (head < 0 && op.includes('.')) head = find(named(`${op.slice(0, op.indexOf('.'))}.*`));
      if (head < 0) throw new Error(`bridge/ext/${f.unit}.md: notes ${op}: PROTOCOL.md has no section for ${op}`);
      let next = head + 1;
      while (next < lines.length && !/^#{1,3} /.test(lines[next]) && lines[next] !== SECTIONS_BEGIN) next++;
      let last = next - 1;
      while (last > head && lines[last].trim() === '') last--;
      lines = [...lines.slice(0, last + 1), ...list.map((l) => `${l} <!-- ext:${f.unit} -->`), ...lines.slice(last + 1)];
    }
  }
  const begin = lines.indexOf(SECTIONS_BEGIN);
  const end = lines.indexOf(SECTIONS_END);
  if (begin < 0 || end < begin) throw new Error('PROTOCOL.md has no section markers');
  const body = fragments.filter((f) => f.section !== '').flatMap((f) => [f.section, '']);
  lines = [...lines.slice(0, begin + 1), ...(body.length > 0 ? ['', ...body] : []), ...lines.slice(end)];
  return lines.join('\n');
}

/** The generated texts, from the registry and the fragments. */
export async function generate() {
  const c = await collect();
  if (c.problems.length > 0) throw new Error(`the units break the contract:\n${c.problems.join('\n')}`);
  const ops = `${JSON.stringify(c.ops, null, 2)}\n`;
  const exportsText = `${JSON.stringify(c.exportJobs, null, 2)}\n`;
  const protocol = assembleProtocol(readFileSync(join(ROOT, PROTOCOL_PATH), 'utf8'), readFragments());
  return { collected: c, files: [[OPS_PATH, ops], [EXPORTS_PATH, exportsText], [PROTOCOL_PATH, protocol]] };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { collected, files } = await generate();
  const stale = files.filter(([p, text]) => readFileSync(join(ROOT, p), 'utf8') !== text);
  if (process.argv.includes('--check')) {
    for (const [p] of stale) console.error(`${p} differs from what scripts/ext/gen.mjs writes`);
    process.exit(stale.length > 0 ? 1 : 0);
  }
  for (const [p, text] of stale) writeFileSync(join(ROOT, p), text);
  console.log(`${collected.units.length} units, ${collected.ops.length} ops, ${Object.keys(collected.exportJobs).length} export jobs; ${stale.length === 0 ? 'nothing changed' : `rewrote ${stale.map(([p]) => p).join(', ')}`}`);
}
